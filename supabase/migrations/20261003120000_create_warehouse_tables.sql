create table public.workshop_warehouse_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  date date not null,
  product_name text not null check (btrim(product_name) <> ''),
  category text,
  quantity numeric not null check (quantity > 0),
  unit text not null check (btrim(unit) <> ''),
  reorder_point numeric check (reorder_point >= 0),
  raw_body_reorder_point numeric check (raw_body_reorder_point >= 0),
  source text,
  reference_number text,
  notes text,
  created_at timestamptz not null default now()
);

create table public.workshop_warehouse_stock (
  user_id uuid not null references auth.users (id) on delete cascade,
  product_key text not null,
  model text not null,
  color text not null,
  item text not null,
  quantity numeric not null default 0 check (quantity >= 0),
  reorder_point numeric check (reorder_point >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, product_key)
);

create table public.workshop_warehouse_movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  product_key text not null,
  model text not null,
  color text not null,
  item text not null,
  type text not null check (type in ('in', 'out')),
  quantity numeric not null check (quantity > 0),
  date date not null,
  reference_number text,
  counterparty text,
  notes text,
  created_at timestamptz not null default now()
);

create table public.workshop_warehouse_models (
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (btrim(name) <> ''),
  created_at timestamptz not null default now(),
  primary key (user_id, name)
);

create index workshop_warehouse_entries_user_date_idx
  on public.workshop_warehouse_entries (user_id, date desc);

create index workshop_warehouse_stock_user_product_idx
  on public.workshop_warehouse_stock (user_id, model, color, item);

create index workshop_warehouse_movements_user_product_date_idx
  on public.workshop_warehouse_movements (user_id, product_key, date desc);

alter table public.workshop_warehouse_entries enable row level security;
alter table public.workshop_warehouse_stock enable row level security;
alter table public.workshop_warehouse_movements enable row level security;
alter table public.workshop_warehouse_models enable row level security;

create policy "users manage their warehouse entries"
  on public.workshop_warehouse_entries for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "users manage their warehouse stock"
  on public.workshop_warehouse_stock for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "users manage their warehouse movements"
  on public.workshop_warehouse_movements for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "users manage their warehouse models"
  on public.workshop_warehouse_models for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

grant usage on schema public to authenticated;
grant select, insert, update, delete on
  public.workshop_warehouse_entries,
  public.workshop_warehouse_stock,
  public.workshop_warehouse_movements,
  public.workshop_warehouse_models
  to authenticated;

grant usage, select on sequence public.workshop_warehouse_entries_id_seq to authenticated;
grant usage, select on sequence public.workshop_warehouse_movements_id_seq to authenticated;